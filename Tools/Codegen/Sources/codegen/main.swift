// Writes the Swift tables from shared/data. Run from the repository root:
//
//   swift run --package-path Tools/Codegen codegen           write the files
//   swift run --package-path Tools/Codegen codegen --check   fail on drift, write nothing

import Foundation

// Static members, not top-level globals: top-level code in main.swift is main-actor isolated.
enum Paths {
  static let calendarJSON = "shared/data/calendar/bs-calendar.json"
  static let calendarOutput = "Sources/NepDate/Calendar.generated.swift"
  static let parsingSpec = "shared/spec/PARSING.md"
  static let wordsOutput = "Sources/NepDate/LenientWords.generated.swift"
  static let patroDirectory = "shared/data/patro"
  static let patroOutput = "Sources/NepDatePatro/Patro.generated.swift"
  /// Serials of BS 2077-01-01 and 2084-08-20, the days PATRO §2 says the data covers.
  static let coverageFirst = 64285
  static let coverageLast = 67077
  /// Era markers and filler words that lenient parsing drops (PARSING §2).
  static let droppedWords = [
    "bs", "b.s.", "b.s", "vs", "v.s.", "v.s", "बि.सं.", "वि.सं.", "बि.सं", "वि.सं", "गते", "मिति",
  ]
}

let header = """
  // Generated by Tools/Codegen. DO NOT EDIT.
  // swift-format-ignore-file


  """

func fail(_ message: String) -> Never {
  FileHandle.standardError.write(Data("codegen: \(message)\n".utf8))
  exit(1)
}

struct CalendarFile: Decodable {
  let minYear: Int
  let maxYear: Int
  let monthLengths: [String: [Int]]
  let epoch: Epoch

  struct Epoch: Decodable {
    let bs: String
    let ad: String
  }

  enum CodingKeys: String, CodingKey {
    case minYear = "min_year"
    case maxYear = "max_year"
    case monthLengths = "month_lengths"
    case epoch
  }
}

struct CalendarInput {
  let years: [(year: Int, lengths: [Int])]
  /// AD date of BS 1901-01-01, `YYYY-MM-DD`.
  let epochAD: String
  /// Unix day of `epochAD`.
  let epochUnixDays: Int
}

/// ALGORITHM §5, Hinnant's days_from_civil. Dev-time only, so plain `Int`.
func daysFromCivil(_ year: Int, _ month: Int, _ day: Int) -> Int {
  let y = month <= 2 ? year - 1 : year
  let era = (y >= 0 ? y : y - 399) / 400
  let yoe = y - era * 400
  let mp = (month + 9) % 12
  let doy = (153 * mp + 2) / 5 + day - 1
  let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy
  return era * 146097 + doe - 719468
}

/// Month lengths per year, in year order, after the checks of S0-02, and the epoch.
func loadCalendar() -> CalendarInput {
  let data: Data
  do {
    data = try Data(contentsOf: URL(fileURLWithPath: Paths.calendarJSON))
  } catch {
    fail("cannot read \(Paths.calendarJSON): \(error)")
  }
  let file: CalendarFile
  do {
    file = try JSONDecoder().decode(CalendarFile.self, from: data)
  } catch {
    fail("cannot decode \(Paths.calendarJSON): \(error)")
  }
  guard file.minYear == 1901 else { fail("min_year is \(file.minYear), expected 1901") }
  guard file.maxYear == 2199 else { fail("max_year is \(file.maxYear), expected 2199") }

  // JSON object order is not guaranteed, so sort the keys as numbers.
  var years: [(year: Int, lengths: [Int])] = []
  for (key, lengths) in file.monthLengths {
    guard let year = Int(key) else { fail("month_lengths key \"\(key)\" is not a year") }
    years.append((year, lengths))
  }
  years.sort { $0.year < $1.year }

  guard years.count == 299 else { fail("month_lengths has \(years.count) years, expected 299") }
  for (offset, entry) in years.enumerated() {
    guard entry.year == 1901 + offset else { fail("year \(1901 + offset) is missing") }
    guard entry.lengths.count == 12 else {
      fail("year \(entry.year) has \(entry.lengths.count) month lengths, expected 12")
    }
    for length in entry.lengths where !(29...32).contains(length) {
      fail("year \(entry.year) has a month of \(length) days, expected 29 to 32")
    }
  }
  guard file.epoch.bs == "1901-01-01" else {
    fail("epoch.bs is \(file.epoch.bs), expected 1901-01-01")
  }
  let parts = file.epoch.ad.split(separator: "-").compactMap { Int($0) }
  guard parts.count == 3 else { fail("epoch.ad \(file.epoch.ad) is not YYYY-MM-DD") }
  return CalendarInput(
    years: years, epochAD: file.epoch.ad, epochUnixDays: daysFromCivil(parts[0], parts[1], parts[2])
  )
}

/// Index of the month that contains each serial, for the bucket table check.
func monthIndexOfSerial(_ monthStart: [Int]) -> [Int] {
  var result: [Int] = []
  result.reserveCapacity(monthStart[monthStart.count - 1])
  for i in 0..<(monthStart.count - 1) {
    for _ in monthStart[i]..<monthStart[i + 1] { result.append(i) }
  }
  return result
}

/// Serial of the first day of every month, plus the number of days in the range.
func monthStarts(_ calendar: CalendarInput) -> [Int] {
  var monthStart = [0]
  for entry in calendar.years {
    for length in entry.lengths { monthStart.append(monthStart[monthStart.count - 1] + length) }
  }
  return monthStart
}

func calendarSource(_ calendar: CalendarInput, header: String) -> String {
  let years = calendar.years
  let monthStart = monthStarts(calendar)
  let totalDays = monthStart[monthStart.count - 1]

  // ADR-0002 §2: entry b is the month of serial b * 16. init(serial:) steps forward at most once,
  // so every serial of a bucket must lie in that month or the next.
  let monthOfSerial = monthIndexOfSerial(monthStart)
  let bucketCount = (totalDays + 15) / 16
  var monthAtBucket: [Int] = []
  for b in 0..<bucketCount {
    let first = monthOfSerial[b * 16]
    for s in (b * 16)..<min(b * 16 + 16, totalDays) where monthOfSerial[s] > first + 1 {
      fail("serial \(s) is two months after the start of its 16-day bucket")
    }
    monthAtBucket.append(first)
  }
  guard monthAtBucket.allSatisfy({ $0 <= Int(UInt16.max) }) else {
    fail("a month index does not fit in UInt16")
  }

  var out = header
  out += """
    /// Calendar tables from `shared/data/calendar/bs-calendar.json` (ADR-0002 §2).
    @usableFromInline
    enum CalendarData {
      @usableFromInline static let minYear = \(years[0].year)
      @usableFromInline static let maxYear = \(years[years.count - 1].year)
      /// Unix day of BS 1901-01-01 (AD \(calendar.epochAD)), ALGORITHM §2.
      @usableFromInline static let epochUnixDays: Int32 = \(calendar.epochUnixDays)
      /// Last valid serial, BS \(years[years.count - 1].year)-12-\(years[years.count - 1].lengths[11]).
      @usableFromInline static let maxSerial: Int32 = \(totalDays - 1)

      /// Serial of the first day of month index `(year - 1901) * 12 + month - 1`.
      /// \(monthStart.count) entries; the last one is the number of days in the range.
      @usableFromInline static let monthStart: [Int32] = [

    """
  for (offset, entry) in years.enumerated() {
    let row = monthStart[(offset * 12)..<(offset * 12 + 12)].map(String.init)
    out += "    \(row.joined(separator: ", ")), // \(entry.year)\n"
  }
  out += "    \(totalDays),\n  ]\n\n"
  out += """
      /// Month index of serial `b * 16`, for `b` in 0..<\(bucketCount).
      @usableFromInline static let monthAtBucket: [UInt16] = [

    """
  var index = 0
  while index < monthAtBucket.count {
    let row = monthAtBucket[index..<min(index + 16, monthAtBucket.count)].map(String.init)
    out += "    " + row.joined(separator: ", ") + ",\n"
    index += 16
  }
  out += "  ]\n}\n"
  return out
}

/// The month names of PARSING §3, in table order, without repeats, after the checks of S3-05.
func loadMonthWords() -> [(word: String, month: Int)] {
  guard let text = try? String(contentsOfFile: Paths.parsingSpec, encoding: .utf8) else {
    fail("cannot read \(Paths.parsingSpec)")
  }
  var inSection = false
  var words: [(word: String, month: Int)] = []
  for line in text.split(separator: "\n", omittingEmptySubsequences: false) {
    if line.hasPrefix("## ") { inSection = line.hasPrefix("## 3.") }
    guard inSection, line.hasPrefix("| ") else { continue }
    let cells = line.split(separator: "|").map { $0.trimmingCharacters(in: .whitespaces) }
    guard cells.count == 2, let month = Int(cells[0]) else { continue }
    for word in cells[1].split(separator: ",") {
      let name = word.trimmingCharacters(in: .whitespaces)
      if !words.contains(where: { $0.word == name }) { words.append((name, month)) }
    }
  }
  guard Set(words.map(\.month)) == Set(1...12) else {
    fail("\(Paths.parsingSpec) §3 does not list names for all 12 months")
  }
  return words
}

/// Byte comparison equals canonical equivalence only when no word changes under NFC or NFD, and
/// lowercasing ASCII bytes equals case-insensitive matching only for lowercase words.
func checkWord(_ word: String) {
  guard word.precomposedStringWithCanonicalMapping == word,
    word.decomposedStringWithCanonicalMapping == word
  else { fail("\"\(word)\" changes under NFC or NFD") }
  guard !word.utf8.contains(where: { (0x41...0x5A).contains($0) }) else {
    fail("\"\(word)\" has an upper-case letter")
  }
}

func wordsSource(_ months: [(word: String, month: Int)], header: String) -> String {
  let words = months + Paths.droppedWords.map { (word: $0, month: 0) }
  var bytes: [UInt8] = []
  var entries: [(offset: Int, length: Int, month: Int, word: String)] = []
  for (word, month) in words {
    checkWord(word)
    entries.append((bytes.count, word.utf8.count, month, word))
    bytes.append(contentsOf: word.utf8)
  }
  guard bytes.count <= Int(UInt16.max) else { fail("lenient words exceed UInt16 offsets") }

  var out = header
  out += """
    /// Words lenient parsing recognises (PARSING §2 and §3), as UTF-8 bytes with Latin letters in
    /// lower case. Byte equality is canonical equivalence here: the generator rejects any word
    /// that NFC or NFD would change.
    @usableFromInline
    enum LenientWords {
      /// Every word's bytes, back to back.
      @usableFromInline static let bytes: [UInt8] = [

    """
  var index = 0
  while index < bytes.count {
    let row = bytes[index..<min(index + 16, bytes.count)].map(String.init)
    out += "    " + row.joined(separator: ", ") + ",\n"
    index += 16
  }
  out += "  ]\n\n"
  out += """
      /// Three entries per word: offset into `bytes`, byte length, and month 1 to 12, or 0 for a
      /// word that is dropped.
      @usableFromInline static let entries: [UInt16] = [

    """
  for entry in entries {
    out += "    \(entry.offset), \(entry.length), \(entry.month), // \(entry.word)\n"
  }
  out += "  ]\n}\n"
  return out
}

struct PatroFile: Decodable {
  let days: [String: Day]

  struct Day: Decodable {
    let tithi: Pair?
    let holiday: Bool?
    let events: [Pair]?
  }

  struct Pair: Decodable, Hashable {
    let np: String
    let en: String
  }
}

/// Serial of a `YYYY-MM-DD` BS day key, or nil when it is not a valid date.
func serialOfKey(_ key: String, monthStart: [Int]) -> Int? {
  let parts = key.split(separator: "-", omittingEmptySubsequences: false)
  guard parts.count == 3, parts.allSatisfy({ !$0.isEmpty && $0.allSatisfy(\.isASCII) }),
    let year = Int(parts[0]), let month = Int(parts[1]), let day = Int(parts[2]),
    (1901...2199).contains(year), (1...12).contains(month)
  else { return nil }
  let index = (year - 1901) * 12 + month - 1
  guard day >= 1, day <= monthStart[index + 1] - monthStart[index] else { return nil }
  return monthStart[index] + day - 1
}

/// A Swift string literal for `text`; the generator rejects control characters.
func swiftLiteral(_ text: String) -> String {
  for scalar in text.unicodeScalars where scalar.value < 0x20 || scalar.value == 0x7F {
    fail("name \(text.debugDescription) has a control character")
  }
  let escaped = text.replacingOccurrences(of: "\\", with: "\\\\")
    .replacingOccurrences(of: "\"", with: "\\\"")
  return "\"\(escaped)\""
}

/// Rows of up to 16 numbers, each indented four spaces and ending with a comma.
func numberRows<C: Collection>(_ values: C) -> String where C.Element == Int {
  let all = Array(values)
  var out = ""
  var index = 0
  while index < all.count {
    out += "    " + all[index..<min(index + 16, all.count)].map(String.init).joined(separator: ", ")
    out += ",\n"
    index += 16
  }
  return out
}

/// The patro tables of ADR-0002 §3 from `shared/data/patro/*.json` (S4-01).
func patroSource(_ calendar: CalendarInput, header: String) -> String {
  let monthStart = monthStarts(calendar)
  let first = Paths.coverageFirst
  let last = Paths.coverageLast
  let count = last - first + 1

  let names = (try? FileManager.default.contentsOfDirectory(atPath: Paths.patroDirectory)) ?? []
  let files = names.compactMap { name -> (year: Int, name: String)? in
    guard name.hasSuffix(".json"), let year = Int(name.dropLast(5)) else { return nil }
    return (year, name)
  }.sorted { $0.year < $1.year }
  guard !files.isEmpty else { fail("no year files in \(Paths.patroDirectory)") }

  var days: [(serial: Int, day: PatroFile.Day)] = []
  var seen = Set<Int>()
  for file in files {
    let path = "\(Paths.patroDirectory)/\(file.name)"
    let decoded: PatroFile
    do {
      decoded = try JSONDecoder().decode(
        PatroFile.self, from: Data(contentsOf: URL(fileURLWithPath: path)))
    } catch {
      fail("cannot read \(path): \(error)")
    }
    for (key, day) in decoded.days {
      guard let serial = serialOfKey(key, monthStart: monthStart) else {
        fail("\(path): day key \(key) is not a valid BS date")
      }
      guard serial >= first, serial <= last else { fail("\(path): day \(key) is outside coverage") }
      guard seen.insert(serial).inserted else { fail("\(path): day \(key) appears twice") }
      days.append((serial, day))
    }
  }
  // JSON object order is not kept by the decoder, so order the days by serial.
  days.sort { $0.serial < $1.serial }

  var nameIDs: [PatroFile.Pair: Int] = [:]
  var nameOrder: [PatroFile.Pair] = []
  func id(of pair: PatroFile.Pair) -> Int {
    if let known = nameIDs[pair] { return known }
    nameIDs[pair] = nameOrder.count
    nameOrder.append(pair)
    return nameOrder.count - 1
  }
  // Tithi names first, so they take ids 0 to 31.
  for entry in days { if let tithi = entry.day.tithi { _ = id(of: tithi) } }
  let tithiCount = nameOrder.count
  guard tithiCount <= 63 else { fail("\(tithiCount) tithi names, at most 63 fit in 6 bits") }

  var dayInfo = [Int](repeating: 0, count: count)
  var eventsOfDay = [[Int]](repeating: [], count: count)
  for entry in days {
    let k = entry.serial - first
    if let tithi = entry.day.tithi { dayInfo[k] |= id(of: tithi) + 1 }
    if entry.day.holiday == true { dayInfo[k] |= 0x80 }
    eventsOfDay[k] = (entry.day.events ?? []).map { id(of: $0) }
  }
  var dayEventStart = [0]
  var eventNameIDs: [Int] = []
  for k in 0..<count {
    eventNameIDs += eventsOfDay[k]
    dayEventStart.append(eventNameIDs.count)
  }
  guard eventNameIDs.count <= Int(UInt16.max) else {
    fail("\(eventNameIDs.count) event entries, at most 65,535 fit in UInt16")
  }

  // Day offsets where a BS month starts, for the comments in dayInfo.
  var monthLabels: [(offset: Int, label: String)] = []
  for i in 0..<(monthStart.count - 1) where monthStart[i] >= first && monthStart[i] <= last {
    let month = i % 12 + 1
    let label = "\(1901 + i / 12)-\(month < 10 ? "0" : "")\(month)-01"
    monthLabels.append((monthStart[i] - first, label))
  }

  var out = header
  out += """
    /// Patro tables from `shared/data/patro/` (ADR-0002 §3). Day `k` is serial `coverageFirst + k`.
    @usableFromInline
    enum PatroData {
      /// Serial of BS 2077-01-01, the first day with patro data.
      @usableFromInline static let coverageFirst: Int32 = \(first)
      /// Serial of BS 2084-08-20, the last day with patro data.
      @usableFromInline static let coverageLast: Int32 = \(last)

      /// One entry per day: bits 0 to 5 are the tithi name id + 1 (0: no tithi), bit 7 is set on a
      /// public holiday.
      @usableFromInline static let dayInfo: [UInt8] = [

    """
  for (index, month) in monthLabels.enumerated() {
    let end = index + 1 < monthLabels.count ? monthLabels[index + 1].offset : count
    out += "    // \(month.label)\n"
    out += numberRows(dayInfo[month.offset..<end])
  }
  out += "  ]\n\n"
  out += """
      /// The events of day `k` are `eventNameIDs[dayEventStart[k] ..< dayEventStart[k + 1]]`.
      @usableFromInline static let dayEventStart: [UInt16] = [

    """
  out += numberRows(dayEventStart)
  out += "  ]\n\n"
  out += """
      /// Name id of each event, days in date order, events in file order.
      @usableFromInline static let eventNameIDs: [UInt16] = [

    """
  out += numberRows(eventNameIDs)
  out += "  ]\n\n"
  out += """
      /// The Nepali and English text of name `id`. Ids 0 to \(tithiCount - 1) are the tithi names.
      @usableFromInline static func name(_ id: UInt16) -> (nepali: String, english: String) {
        switch id {

    """
  for (index, pair) in nameOrder.enumerated() {
    out += "    case \(index): return (\(swiftLiteral(pair.np)), \(swiftLiteral(pair.en)))\n"
  }
  out += "    default: return (\"\", \"\")\n    }\n  }\n}\n"

  let stringBytes = nameOrder.reduce(0) { $0 + $1.np.utf8.count + $1.en.utf8.count }
  print(
    "codegen: dayInfo \(count) bytes, dayEventStart \(2 * dayEventStart.count) bytes, "
      + "eventNameIDs \(2 * eventNameIDs.count) bytes, \(nameOrder.count) names "
      + "(\(stringBytes) bytes of UTF-8)")
  return out
}

/// Prints the first line where `expected` and the file on disk differ. Returns true when equal.
func matchesDisk(_ expected: String, path: String) -> Bool {
  guard let disk = FileManager.default.contents(atPath: path) else {
    print("codegen: \(path) is missing")
    return false
  }
  if disk == Data(expected.utf8) { return true }
  let actualLines = String(decoding: disk, as: UTF8.self).split(
    separator: "\n", omittingEmptySubsequences: false)
  let expectedLines = expected.split(separator: "\n", omittingEmptySubsequences: false)
  var line = 0
  while line < actualLines.count, line < expectedLines.count,
    actualLines[line] == expectedLines[line]
  {
    line += 1
  }
  let want = line < expectedLines.count ? String(expectedLines[line]) : "<end of file>"
  let got = line < actualLines.count ? String(actualLines[line]) : "<end of file>"
  print("codegen: \(path) differs from the generator at line \(line + 1)")
  print("  expected: \(want.debugDescription)")
  print("  actual:   \(got.debugDescription)")
  return false
}

let arguments = Array(CommandLine.arguments.dropFirst())
let check = arguments == ["--check"]
guard arguments.isEmpty || check else { fail("usage: codegen [--check]") }
guard FileManager.default.fileExists(atPath: "shared/VERSION") else {
  print("codegen: run from the repository root")
  exit(1)
}

let calendar = loadCalendar()
let outputs = [
  (Paths.calendarOutput, calendarSource(calendar, header: header)),
  (Paths.wordsOutput, wordsSource(loadMonthWords(), header: header)),
  (Paths.patroOutput, patroSource(calendar, header: header)),
]

if check {
  // Check every file before exiting, so one run reports all drift.
  let drifted = outputs.filter { !matchesDisk($0.1, path: $0.0) }
  if !drifted.isEmpty {
    print("codegen: run `swift run --package-path Tools/Codegen codegen` and commit the result")
    exit(1)
  }
  print("codegen: generated files are up to date")
} else {
  for (path, source) in outputs {
    do {
      try Data(source.utf8).write(to: URL(fileURLWithPath: path), options: .atomic)
    } catch {
      fail("cannot write \(path): \(error)")
    }
    print("codegen: wrote \(path)")
  }
}
